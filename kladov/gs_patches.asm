; GS-патчи Кладова — аннотированный разбор.
;
; Источники:
;   zx_bin/kladov128gs.bin  — итоговый 128K-образ (патчи поверх kladov128.bin);
;   zx_src/Elite3GS.trd     — GS-дискета с дополнительным сектором кода.
;
; Обозначения:
;   `*` — байт отличается от обычного образа/дискеты;
;   адреса `0x4000..0x7FFF` показаны в логической памяти; физический offset
;   в образе = адрес + 0x10000 (банк 5).
;
; Эмулятор НЕ синтезирует сэмплы General Sound. Порты только обеспечивают
; протокол, а команда `0x39` превращается в нативный `sfx::Sfx::Gs(A)`:
;   OUT (0xB3),A → `gs_latch = A`;
;   OUT (0xBB),A → `gs_command = A`, при `A == 0x39` в очередь звука идёт `gs_latch`;
;   IN A,(0xBB)  → одно чтение «занято» (0x81), затем 0x00 (готово).
; ===========================================================================

; ---------------------------------------------------------------------------
; 0x7344 — подпрограмма «проиграть номер из A».
;
; Обычный код здесь делал настройку скорости/углов (`LD B,6`, `LD E,0`, ...).
; В GS-версии Area полностью заменена на handshake:
;   0x7344 — вход с фиксированным номером 1 (переход из `InitSpeedAngle`);
;   0x7346 — вход с номером в A (CALL/JP из игровых точек ниже).
; ---------------------------------------------------------------------------
* 7344: 3e 01                LD A,1          ; номер звука по умолчанию
* 7346: d3 b3                OUT (0x00b3),A  ; защёлка = номер звука
* 7348: 3e 39                LD A,0x39       ; команда «проиграть»
* 734A: d3 bb                OUT (0x00bb),A
* 734C: db bb                IN A,(0x00bb)   ; ожидание готовности
* 734E: 0f                   RRCA            ; carry = бит 0 = «занято»
* 734F: 38 fb                JR c,0x734c
