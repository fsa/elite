//! Цвета нативного вида из кабины.

/// Цвет фона (непрозрачный чёрный).
pub(super) const BG: u32 = 0xFF00_0000;
/// Циан — линии объектов и перекрестие.
pub(super) const CYAN: u32 = 0xFF00_FFFF;
/// Красный — лазеры и опасность.
pub(super) const RED: u32 = 0xFFFF_4040;
/// Жёлтый — цвет луча выстрела противника.
pub(super) const ENEMY_BEAM: u32 = 0xFFFF_A020;
/// Цвет звезды по умолчанию — почти белый (пока цвет системы неизвестен).
pub(super) const SUN_COLOR: u32 = 0xFFFF_FFD7;
/// Планета по умолчанию — очень тёмный зелёный диск.
pub(super) const PLANET_COLOR: u32 = 0xFF00_2000;

/// Ободок планеты: тот же зелёный тон, но заметно ярче заливки.
///
/// В оригинале планета рисуется только контуром, поэтому ободок сохраняет
/// узнаваемую «рамку» и не даёт диску слиться с чёрным космосом.
pub(super) fn planet_rim(color: u32) -> u32 {
    let g = ((color >> 8) & 0xFF) + 0x58;
    0xFF00_0000 | (g.min(0xFF) << 8)
}
/// Цвет надписей в переходе: приглушённый циан, чтобы не спорить с HUD.
pub(super) const TRANSITION_TEXT: u32 = 0xFF80_FFFF;
/// Белый — цвет подписи направления вида и строки гиперпрыжка, как у
/// надписей на заставке (`E L I T E`, приглашение).
pub(super) const VIEW_LABEL_COLOR: u32 = 0xFFD7_D7D7;
/// Цвет тоннеля гиперпрыжка.
pub(super) const WARP_RING_COLOR: u32 = 0xFF40_A0FF;
/// Кольца тоннеля станции — белые, как в оригинале.
pub(super) const STATION_RING_COLOR: u32 = 0xFFFF_FFFF;
/// Окантовка звезды — чистый белый.
pub(super) const STAR_RIM_COLOR: u32 = 0xFFFF_FFFF;

/// Цвет частицы взрыва при `t = 1` (только что уничтоженный объект):
/// раскалённый жёлто-белый.
const EXPLOSION_HOT: (f32, f32, f32) = (255.0, 214.0, 120.0);

/// Цвет частицы облака: `t` — доля оставшейся жизни (`1..0`).
///
/// Сначала частица почти белая, затем остывает до красного и плавно гаснет.
/// Яркость убывает как `sqrt(t)`, поэтому облако остаётся видимым почти до
/// конца двух секунд и растворяется без резкой границы.
pub(super) fn explosion_color(t: f32) -> u32 {
    let t = t.clamp(0.0, 1.0);
    let fade = t.sqrt();
    let r = (EXPLOSION_HOT.0 * fade) as u32;
    let g = (EXPLOSION_HOT.1 * fade * t) as u32;
    let b = (EXPLOSION_HOT.2 * fade * t * t) as u32;
    0xFF00_0000 | (r << 16) | (g << 8) | b
}

/// Очень тёмный зелёный оттенок планеты с небольшой вариацией яркости по
/// системе.
///
/// Канал красного и синего всегда нулевой, поэтому планета не совпадает по
/// цвету ни с белыми кораблями, ни с циановой станцией, ни с жёлтым солнцем.
pub(super) fn planet_green(seed: u32) -> u32 {
    let g = 0x20 + ((seed >> 8) & 0x0F);
    0xFF00_0000 | (g << 8)
}

/// Цвет звезды системы: почти белый диск с лёгким оттенком того цвета,
/// которым эта система показана на карте галактики.
///
/// Каждый канал смешивается с белым в пропорции 85/15, поэтому звезда
/// остаётся яркой и не спорит с белыми кораблями, но всё же отличается по
/// оттенку от системы к системе.
pub(super) fn sun_tint(system_color: u32) -> u32 {
    let mix = |c: u32| 0xD9 + c * 0x26 / 0xFF;
    0xFF00_0000
        | (mix((system_color >> 16) & 0xFF) << 16)
        | (mix((system_color >> 8) & 0xFF) << 8)
        | mix(system_color & 0xFF)
}
