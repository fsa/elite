//! Полноэкранная (HD) поверхность отрисовки.
//!
//! Кадр игры рисуется старым кодом по-прежнему в 256x192 (видеопамять
//! ZX Spectrum). В игре показывается кадр целиком — и вид из кабины (верхние
//! 128 строк), и родная растровая панель оригинала (нижние 64 строки) —
//! целым множителем (nearest neighbour) по центру окна. Рядом существует
//! HD-слой [`Frame`] — поверхность в разрешении всего окна, в которую
//! нативные (Rust) реализации могут рисовать в полном разрешении (меню,
//! приборная панель, экран полёта, гладкие линии, крупный текст).
//!
//! Слой очищается перед каждым кадром, нативные хуки рисуют в него во
//! время эмуляции ([`Spectrum::hd`](crate::machine::Spectrum)), а при
//! показе непрозрачные пиксели слоя (старший байт != 0) накладываются
//! поверх масштабированного ZX-кадра.

/// Ширина кадра ZX Spectrum.
pub const ZX_W: usize = 256;
/// Высота кадра ZX Spectrum.
pub const ZX_H: usize = 192;

/// Ширина отладочной полосы: кадр эмулятора выводится в ней 1:1, как на
/// экране ZX Spectrum (256 пикселей). Полоса занимает правый край окна,
/// ниже миниатюры остаётся чёрный фон для будущей отладочной информации.
pub const DEBUG_W: usize = ZX_W;

/// Левый край отладочной полосы в окне шириной `win_w`. Если окно уже
/// полосы, полоса прижимается к левому краю и обрезается по окну.
pub fn debug_panel_x(win_w: u32) -> u32 {
    win_w.saturating_sub(DEBUG_W as u32)
}

/// Размер игровой области окна: при включённой отладке справа остаётся
/// полоса [`DEBUG_W`], иначе игра занимает всё окно.
pub fn game_area(win_w: u32, win_h: u32, debug: bool) -> (u32, u32) {
    let w = if debug {
        win_w.saturating_sub(DEBUG_W as u32)
    } else {
        win_w
    };
    (w, win_h)
}

/// Прозрачный пиксель HD-слоя: накладывается только непрозрачный цвет
/// (со старшим байтом != 0, например `0xFFRRGGBB`).
pub const TRANSPARENT: u32 = 0;

/// Область показа ZX-кадра в окне: целый масштаб и положение по центру.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Layout {
    /// Целый масштаб (>= 1): пиксели ZX строго квадратные и чёткие.
    pub scale: usize,
    /// Левый верхний угол области в пикселях окна.
    pub x: u32,
    pub y: u32,
    /// Размер области (256*scale x 192*scale, обрезается по окну).
    pub w: u32,
    pub h: u32,
}

/// Рассчитать область показа для окна `win_w` x `win_h`.
///
/// Масштаб — наибольшее целое, влезающее по обеим осям (в полноэкранном
/// режиме 1920x1080 — это x5, картинка 1280x960 по центру). Если окно
/// меньше кадра ZX, масштаб принудительно 1, а область обрезается по окну.
pub fn layout(win_w: u32, win_h: u32) -> Layout {
    let scale = ((win_w as usize / ZX_W).min(win_h as usize / ZX_H)).max(1);
    let w = (ZX_W * scale).min(win_w as usize) as u32;
    let h = (ZX_H * scale).min(win_h as usize) as u32;
    Layout {
        scale,
        x: (win_w - w) / 2,
        y: (win_h - h) / 2,
        w,
        h,
    }
}

/// Раскладка ZX-кадра в игровой области окна. При отладке игра сдвигается
/// влево, чтобы справа поместилась полоса [`DEBUG_W`].
pub fn layout_for(win_w: u32, win_h: u32, debug: bool) -> Layout {
    let (w, h) = game_area(win_w, win_h, debug);
    layout(w, h)
}

