//! Образы, встраиваемые в исполняемый файл на этапе сборки.
//!
//! Это позволяет запускать игру без внешних файлов: ROM ZX Spectrum 48K и
//! готовый 128K-образ холодного старта (`zx_bin/kladov128gs.bin`) становятся
//! частью бинарника. Файл сохранил старое имя, но теперь содержит не снапшот
//! работающей игры, а состояние сразу после загрузчика. TR-DOS в
//! рантайме не участвует: его диски нужны только офлайн-генератору
//! `tools/make_cold_image.py`. Оригинальный 128K-снапшот остаётся в
//! репозитории только для тестов эквивалентности нативных рутин. Пути в
//! `include_bytes!` относительные к этому файлу, поэтому сборка не зависит от
//! текущего каталога.

/// Все восемь банков ОЗУ версии Кладова с GS-патчами (по 16K, физический
/// порядок 0..7). Это состояние сразу после однократного применения
/// загрузчика с `Elite3GS.trd`: игра ещё не исполнила ни одного кадра.
///
/// Банк 5 отображается по `0x4000`, банк 2 — по `0x8000`, а банк из младших
/// трёх битов порта `0x7FFD` — по `0xC000`.
pub const COLD_IMAGE: &[u8] = include_bytes!("../zx_bin/kladov128gs.bin");

/// Оригинальный образ без GS-патчей. Используется тестами эквивалентности
/// нативных рутин: они сравнивают поведение с исходным кодом игры.
pub const KLADOV_IMAGE: &[u8] = include_bytes!("../zx_bin/kladov128.bin");

/// Начальное значение порта `0x7FFD` из заголовка SNA-снапшота: банк 0 по
/// `0xC000`, экран из банка 5, основная ROM.
#[cfg(test)]
pub const KLADOV_PAGE_REG: u8 = 0x10;

/// Стандартная ROM ZX Spectrum 48K.
pub const ROM_48: &[u8] = include_bytes!("../zx_bin/48.rom");

const _: () = assert!(COLD_IMAGE.len() == 0x2_0000);
const _: () = assert!(KLADOV_IMAGE.len() == 0x2_0000);
const _: () = assert!(ROM_48.len() == 0x4000);
