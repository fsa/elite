//! Образы, встраиваемые в исполняемый файл на этапе сборки.
//!
//! Это позволяет запускать игру без внешних файлов: 128K-образ RAM версии
//! Кладова и ROM ZX Spectrum 48K становятся частью бинарника. Пути в
//! `include_bytes!` относительные к этому файлу, поэтому сборка не зависит от
//! текущего каталога.

/// Все восемь банков ОЗУ версии Кладова (по 16K, физический порядок 0..7).
/// Банк 5 отображается по `0x4000`, банк 2 — по `0x8000`, а банк из младших
/// трёх битов [`KLADOV_PAGE_REG`] — по `0xC000`.
///
/// Оригинальный образ без GS-патчей. Используется тестами эквивалентности
/// нативных рутин: они сравнивают поведение с исходным кодом игры.
pub const KLADOV_IMAGE: &[u8] = include_bytes!("../zx_bin/kladov128.bin");

/// Версия с поддержкой General Sound: тот же снапшот состояния игры, что и
/// `KLADOV_IMAGE`, но с патчами портов `0xB3`/`0xBB` и кодом работы со
/// звуковым устройством. Используется по умолчанию при запуске игры.
pub const KLADOV_GS_IMAGE: &[u8] = include_bytes!("../zx_bin/kladov128gs.bin");

/// Начальное значение порта `0x7FFD` из заголовка SNA-снапшота: банк 0 по
/// `0xC000`, экран из банка 5, основная ROM.
pub const KLADOV_PAGE_REG: u8 = 0x10;

/// Стандартная ROM ZX Spectrum 48K.
pub const ROM_48: &[u8] = include_bytes!("../zx_bin/48.rom");

const _: () = assert!(KLADOV_IMAGE.len() == 0x2_0000);
const _: () = assert!(KLADOV_GS_IMAGE.len() == 0x2_0000);
const _: () = assert!(ROM_48.len() == 0x4000);
